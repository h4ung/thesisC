"""Generate a small SYNTHETIC dataset with the same schema as the real pipeline.

!!! SYNTHETIC DATA -- FOR PIPELINE TESTING ONLY. NEVER REPORT RESULTS FROM IT. !!!

It lets the full train -> test -> stratify -> ablate -> collect pipeline run
end-to-end (CI, a laptop, or a quick check after a code change) without
credentialed MIMIC-IV access. Event times are drawn from a proportional-hazards
model whose risk depends on baseline eGFR, age, diabetes and an amplitude
feature planted in the ECG, so a working model should reach a C-index clearly
above 0.5 and the ECG/EHR ablations should move in the expected direction.

Usage
-----
python scripts/make_synthetic_dataset.py --out_dir dataset/synthetic --n_subjects 600
python run.py --config configs/ckd_prognosis.yaml --root_path dataset/synthetic ...
"""

import argparse
import json
import os

import numpy as np
import pandas as pd

LABS = ["creatinine", "egfr", "bun", "potassium", "sodium", "bicarbonate",
        "hemoglobin", "glucose", "albumin"]
STATS = ["last", "min", "max", "mean", "slope", "n"]
CMB = ["diabetes", "hypertension", "heart_failure", "ischemic_heart", "anemia"]


def make(out_dir, n_subjects=600, studies_per_subject=(1, 3), horizon=730.0,
         n_intervals=8, ecg_len=2500, n_leads=12, seed=0):
    rng = np.random.default_rng(seed)
    os.makedirs(os.path.join(out_dir, "ecg_npy"), exist_ok=True)
    rows = []
    study_id = 10_000_000
    for sid in range(1, n_subjects + 1):
        age = rng.uniform(30, 85)
        female = rng.random() < 0.5
        egfr = np.clip(rng.normal(85, 15), 60, 130)
        diab = rng.random() < 0.25
        htn = rng.random() < 0.4
        ecg_marker = rng.normal()                     # latent "ECG" risk signal
        lin = (-0.05 * (egfr - 85) + 0.03 * (age - 60) + 0.8 * diab + 0.4 * htn
               + 0.6 * ecg_marker)
        for _ in range(rng.integers(studies_per_subject[0], studies_per_subject[1] + 1)):
            study_id += 1
            # event time from an exponential PH model; censoring uniform on [60, 1800]
            rate = 1 / 2500 * np.exp(lin)
            t_event = rng.exponential(1 / rate)
            t_cens = rng.uniform(60, 1800)
            t = min(t_event, t_cens)
            e = int(t_event <= t_cens)
            t = max(t, 31.0)                          # respect the 30-day blanking gap
            # ECG: noise + a sinusoid whose amplitude encodes the latent marker
            tt = np.arange(ecg_len) / 250.0
            sig = rng.normal(0, 1, (n_leads, ecg_len)).astype(np.float32)
            sig += (1.0 + 0.8 * ecg_marker) * np.sin(2 * np.pi * 1.2 * tt)[None, :]
            npy = os.path.join(out_dir, "ecg_npy", f"{study_id}.npy")
            np.save(npy, sig.astype(np.float32))

            label = int(e == 1 and t <= horizon)
            eligible = int(label == 1 or t >= horizon)
            edges = np.linspace(0, horizon, n_intervals + 1)
            ebin = int(np.clip(np.digitize(min(t, horizon - 1e-6), edges) - 1, 0, n_intervals - 1))
            r = {"subject_id": sid, "study_id": study_id, "ecg_npy": npy,
                 "t0": pd.Timestamp("2150-01-01"), "label_binary": label,
                 "eligible_binary": eligible, "event_time_days": float(t),
                 "event_indicator": e, "event_bin": ebin,
                 "age_at_t0": age, "sex_female": float(female)}
            for lab in LABS:
                base = {"egfr": egfr, "creatinine": 1.0 - (egfr - 85) / 100}.get(lab, rng.normal())
                for s in STATS:
                    r[f"{lab}_{s}"] = (float(rng.integers(1, 6)) if s == "n"
                                       else float(base + rng.normal(0, 0.1)))
            for c in CMB:
                r[f"cmb_{c}"] = float({"diabetes": diab, "hypertension": htn}.get(c, rng.random() < 0.1))
            rows.append(r)

    df = pd.DataFrame(rows)
    # subject-level split, stratified on any-positive
    subj = df.groupby("subject_id")["label_binary"].max()
    split = {}
    for lab in (0, 1):
        ids = subj[subj == lab].index.to_numpy()
        rng.shuffle(ids)
        n_tr, n_va = int(0.6 * len(ids)), int(0.2 * len(ids))
        split.update({i: "train" for i in ids[:n_tr]})
        split.update({i: "val" for i in ids[n_tr:n_tr + n_va]})
        split.update({i: "test" for i in ids[n_tr + n_va:]})
    df["split"] = df["subject_id"].map(split)
    df.to_parquet(os.path.join(out_dir, "ckd_dataset_split.parquet"), index=False)
    feat = ["age_at_t0", "sex_female"] + [f"{l}_{s}" for l in LABS for s in STATS] + \
           [f"cmb_{c}" for c in CMB]
    json.dump(feat, open(os.path.join(out_dir, "ehr_feature_columns.json"), "w"), indent=2)
    with open(os.path.join(out_dir, "SYNTHETIC_DATA_README.txt"), "w") as f:
        f.write("SYNTHETIC DATA generated by scripts/make_synthetic_dataset.py. "
                "For pipeline testing only; results are meaningless.\n")
    print(f"[synthetic] {len(df)} rows / {n_subjects} subjects -> {out_dir} "
          f"(event rate by horizon {df['label_binary'].mean():.2f})")
    return df


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--out_dir", default="dataset/synthetic")
    p.add_argument("--n_subjects", type=int, default=600)
    p.add_argument("--horizon_days", type=float, default=730)
    p.add_argument("--n_intervals", type=int, default=8)
    p.add_argument("--seed", type=int, default=0)
    a = p.parse_args()
    make(a.out_dir, a.n_subjects, horizon=a.horizon_days, n_intervals=a.n_intervals, seed=a.seed)
